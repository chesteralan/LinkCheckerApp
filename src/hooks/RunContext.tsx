import { createContext, useState, useCallback, useEffect, useRef, type ReactNode } from 'react'
import { listen, type UnlistenFn } from '@tauri-apps/api/event'
import { runAudit, runQuickAudit, cancelRun, getRunResults } from '@/lib/tauri'
import type {
  PageResult,
  AuditRun,
  SelectorCheck,
  RunProgressEvent,
  RunResultEvent,
  RunCompleteEvent,
  RunCancelledEvent,
  RunErrorEvent,
} from '@/types'

export interface RunnerState {
  running: boolean
  run: AuditRun | null
  progress: { checked: number; total: number } | null
  runPagePath: string | null
  /**
   * Page that started the current (or last) run: `/audits/<id>` or a quick-audit path. Unlike
   * `runPagePath` it survives the run finishing, so pages can tell whether `run` is theirs (A-27).
   */
  ownerKey: string | null
  /** Id of the current (or last) run, generated by the frontend. */
  runId: string | null
  /** Why the last run failed to start or finish, if it did. */
  error: string | null
}

type RunConfig = {
  mode: string
  batchSize: number
  timeoutSecs: number
  headers?: Record<string, string>
  cookies?: { key: string; value: string }[]
}

export interface RunContextValue extends RunnerState {
  start: (auditId: string, originOverride?: string, urlPostfix?: string) => Promise<void>
  startQuick: (
    urls: string[],
    checks: SelectorCheck[],
    config: RunConfig,
    originOverride?: string,
    urlPostfix?: string,
    returnPath?: string,
  ) => Promise<void>
  cancel: () => Promise<void>
  clearError: () => void
}

export const RunContext = createContext<RunContextValue | null>(null)

function newRunId(): string {
  if (typeof crypto !== 'undefined' && typeof crypto.randomUUID === 'function') return crypto.randomUUID()
  // RFC 4122 v4 fallback so the backend accepts it as a UUID.
  return 'xxxxxxxx-xxxx-4xxx-yxxx-xxxxxxxxxxxx'.replace(/[xy]/g, (c) => {
    const r = (Math.random() * 16) | 0
    return (c === 'x' ? r : (r & 0x3) | 0x8).toString(16)
  })
}

function errorMessage(e: unknown): string {
  if (e instanceof Error) return e.message
  return typeof e === 'string' ? e : JSON.stringify(e)
}

/** Removes the routing key the backend adds to run:result payloads. */
function toPageResult(payload: RunResultEvent): PageResult {
  const { runId: _runId, ...result } = payload
  void _runId
  return result
}

const IDLE: RunnerState = {
  running: false,
  run: null,
  progress: null,
  runPagePath: null,
  ownerKey: null,
  runId: null,
  error: null,
}

export function RunProvider({ children }: { children: ReactNode }) {
  const [state, setState] = useState<RunnerState>(IDLE)
  const unlisteners = useRef<UnlistenFn[]>([])
  // Both refs are set synchronously in start()/cancel() so a second start
  // cannot race with the first (A-15). Events for any other run are ignored.
  const runningRef = useRef(false)
  const currentRunIdRef = useRef<string | null>(null)
  // Set once run:complete / run:error has been handled for a run.
  const settledRunIdRef = useRef<string | null>(null)

  const cleanup = useCallback(() => {
    for (const unlisten of unlisteners.current) {
      unlisten()
    }
    unlisteners.current = []
  }, [])

  useEffect(() => {
    return () => {
      cleanup()
    }
  }, [cleanup])

  /** Ends the run `runId` if it is still the current one. */
  const finish = useCallback(
    (runId: string, update: (s: RunnerState) => RunnerState) => {
      if (currentRunIdRef.current !== runId) return
      settledRunIdRef.current = runId
      runningRef.current = false
      setState(update)
      cleanup()
    },
    [cleanup],
  )

  const setupListeners = useCallback(
    async (runId: string, auditId: string) => {
      const isCurrent = (id: string | undefined) => id === runId && currentRunIdRef.current === runId
      const fns: UnlistenFn[] = []
      try {
        fns.push(
          await listen<RunResultEvent>('run:result', (event) => {
            if (!isCurrent(event.payload.runId)) return
            const result = toPageResult(event.payload)
            setState((s) => ({
              ...s,
              run: s.run
                ? { ...s.run, results: [...s.run.results, result] }
                : {
                    id: runId,
                    auditId,
                    startedAt: new Date().toISOString(),
                    completedAt: null,
                    status: 'running',
                    results: [result],
                    summary: { total: 0, passed: 0, failed: 0, errored: 0, avgResponseTimeMs: 0 },
                  },
            }))
          }),
        )

        fns.push(
          await listen<RunProgressEvent>('run:progress', (event) => {
            if (!isCurrent(event.payload.runId)) return
            const { checked, total } = event.payload
            setState((s) => ({ ...s, progress: { checked, total } }))
          }),
        )

        fns.push(
          await listen<RunCompleteEvent>('run:complete', (event) => {
            if (!isCurrent(event.payload.runId)) return
            const { runId: _runId, ...run } = event.payload
            void _runId
            finish(runId, (s) => ({ ...s, running: false, run, progress: null, runPagePath: null }))
          }),
        )

        // run:cancelled is followed by run:complete with the saved partial run;
        // stop the "Running" indicator now and keep listening for run:complete.
        fns.push(
          await listen<RunCancelledEvent>('run:cancelled', (event) => {
            if (!isCurrent(event.payload?.runId)) return
            runningRef.current = false
            setState((s) => ({ ...s, running: false, progress: null, runPagePath: null }))
          }),
        )

        fns.push(
          await listen<RunErrorEvent>('run:error', (event) => {
            if (!isCurrent(event.payload?.runId)) return
            const message = event.payload.message
            finish(runId, (s) => ({ ...s, running: false, progress: null, runPagePath: null, error: message }))
          }),
        )
      } catch (e) {
        for (const fn of fns) fn()
        throw e
      }
      // A newer run may have started while we were awaiting listen().
      if (currentRunIdRef.current !== runId) {
        for (const fn of fns) fn()
        return
      }
      unlisteners.current = fns
    },
    [finish],
  )

  /** Cancels any active run and makes `runId` the current one. */
  const beginRun = useCallback(
    async (runId: string, runPagePath: string | null) => {
      const previous = currentRunIdRef.current
      const wasRunning = runningRef.current
      currentRunIdRef.current = runId
      runningRef.current = true
      cleanup()
      setState({ running: true, run: null, progress: null, runPagePath, ownerKey: runPagePath, runId, error: null })
      if (wasRunning && previous) {
        try {
          await cancelRun(previous)
        } catch (e) {
          console.error('Failed to cancel previous run', e)
        }
      }
    },
    [cleanup],
  )

  /** Runs `invoke` and turns a rejection into an error state for `runId`. */
  const execute = useCallback(
    async (runId: string, auditId: string, invoke: () => Promise<string>) => {
      try {
        await setupListeners(runId, auditId)
        await invoke()
      } catch (e) {
        const message = errorMessage(e)
        console.error('Run failed', e)
        finish(runId, (s) => ({ ...s, running: false, progress: null, runPagePath: null, error: message }))
        return
      }
      // The promise resolves after the final record is saved. Events and IPC
      // replies travel separately, so run:complete may not have arrived yet:
      // give it a moment, then load the saved run directly.
      if (currentRunIdRef.current !== runId || settledRunIdRef.current === runId) return
      await new Promise((resolve) => setTimeout(resolve, 250))
      if (currentRunIdRef.current !== runId || settledRunIdRef.current === runId) return
      try {
        const run = await getRunResults(runId)
        finish(runId, (s) => ({ ...s, running: false, run, progress: null, runPagePath: null }))
      } catch {
        finish(runId, (s) => ({ ...s, running: false, progress: null, runPagePath: null }))
      }
    },
    [setupListeners, finish],
  )

  const start = useCallback(
    async (auditId: string, originOverride?: string, urlPostfix?: string) => {
      const runId = newRunId()
      await beginRun(runId, `/audits/${auditId}`)
      if (currentRunIdRef.current !== runId) return
      await execute(runId, auditId, () => runAudit(auditId, originOverride, urlPostfix, runId))
    },
    [beginRun, execute],
  )

  const startQuick = useCallback(
    async (
      urls: string[],
      checks: SelectorCheck[],
      config: RunConfig,
      originOverride?: string,
      urlPostfix?: string,
      returnPath?: string,
    ) => {
      const runId = newRunId()
      await beginRun(runId, returnPath ?? null)
      if (currentRunIdRef.current !== runId) return
      await execute(runId, '', () => runQuickAudit({ urls, checks, config, originOverride, urlPostfix, runId }))
    },
    [beginRun, execute],
  )

  const cancel = useCallback(async () => {
    const runId = currentRunIdRef.current
    if (!runId) return
    // Keep listeners attached so the saved partial run still arrives via
    // run:complete; only the "Running" indicator is cleared here.
    runningRef.current = false
    setState((s) => ({ ...s, running: false, progress: null, runPagePath: null }))
    try {
      await cancelRun(runId)
    } catch (e) {
      const message = errorMessage(e)
      console.error('Failed to cancel run', e)
      setState((s) => ({ ...s, error: `Could not cancel the run: ${message}` }))
    }
  }, [])

  const clearError = useCallback(() => setState((s) => ({ ...s, error: null })), [])

  return (
    <RunContext.Provider value={{ ...state, start, startQuick, cancel, clearError }}>{children}</RunContext.Provider>
  )
}

